const THEME_MAP = new Map(APP_THEMES.map((theme) => [theme.id, theme]))

export function getTheme(id: unknown): AppTheme {
  return THEME_MAP.get(normalizeColorTheme(id)) ?? THEME_MAP.get(DEFAULT_COLOR_THEME)!
}

export function themesInCategory(category: ThemeCategory): AppTheme[] {
  return APP_THEMES.filter((theme) => theme.category === category)
}

export function themeCssVars(theme: AppTheme): Record<string, string> {
  return {
    '--erp-color-primary': theme.colorPrimary,
    '--erp-color-primary-hover': theme.colorPrimaryHover,
    '--erp-color-primary-dark': theme.colorPrimaryDark,
    '--erp-color-primary-bg': theme.colorPrimaryBg,
    '--erp-nav-bg': theme.navBg,
    '--erp-brand-text': theme.brandText,
    '--erp-nav-text': theme.navText,
    '--erp-nav-text-muted': theme.navTextMuted,
    '--erp-nav-border': theme.navBorder,
    '--erp-nav-footer-bg': theme.navFooterBg,
    '--erp-content-bg': theme.contentBg,
    '--erp-content-gradient': theme.contentGradient,
    '--erp-hero-gradient': theme.heroGradient,
  }
}

export function buildAntdTheme(theme: AppTheme): ThemeConfig {
  const isDarkNav = theme.navTheme === 'dark'
  return {
    token: {
      colorPrimary: theme.colorPrimary,
    },
    components: {
      Layout: {
        headerBg: theme.navBg,
        siderBg: theme.navBg,
        bodyBg: 'transparent',
      },
      Menu: isDarkNav
        ? {
            darkItemBg: theme.navBg,
            darkSubMenuItemBg: theme.navBg,
            darkItemSelectedBg: theme.colorPrimary,
            darkPopupBg: theme.navBg,
          }
        : {
            itemBg: 'transparent',
            subMenuItemBg: theme.navBg,
            itemSelectedBg: theme.colorPrimaryBg,
            itemSelectedColor: theme.colorPrimary,
            horizontalItemSelectedBg: theme.colorPrimaryBg,
            horizontalItemSelectedColor: theme.colorPrimary,
          },
    },
  }
}
