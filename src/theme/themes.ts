const THEME_ID_SET = new Set<string>(COLOR_THEME_IDS)

export function normalizeColorTheme(value: unknown): ColorThemeId {
  const id = String(value || DEFAULT_COLOR_THEME).trim()
  return THEME_ID_SET.has(id) ? (id as ColorThemeId) : DEFAULT_COLOR_THEME
}

